async def main():
    from app.core.database import AsyncSessionLocal

    print("=" * 60)
    print("[Fix Visit Notes] Updating home_visits observations...")
    print("=" * 60)

    async with AsyncSessionLocal() as session:
        # Count records
        total = (await session.execute(
            text("SELECT COUNT(*) FROM home_visits")
        )).scalar()
        print(f"  Total visits in DB: {total}")

        # Get all visits with their type
        rows = (await session.execute(text(
            "SELECT id, visit_type FROM home_visits ORDER BY visit_date DESC"
        ))).fetchall()

        updated = 0
        for row in rows:
            vid, vtype = str(row[0]), str(row[1] or "routine")
            notes_pool = NOTES_BY_TYPE.get(vtype, DEFAULT_NOTES)
            recs_pool  = RECS_BY_TYPE.get(vtype, DEFAULT_RECS)
            note = random.choice(notes_pool)
            rec  = random.choice(recs_pool)

            await session.execute(text("""
                UPDATE home_visits
                SET observation    = :note,
                    recommendation = :rec,
                    updated_at     = NOW()
                WHERE id = :id
            """), {"note": note, "rec": rec, "id": vid})
            updated += 1

        await session.commit()

    print(f"\n  [OK] Updated {updated} visit records")
    print("\n  Sample per type:")
    for vtype, notes in NOTES_BY_TYPE.items():
        print(f"    {vtype}: {notes[0][:50]}...")
    print("\n[DONE] Restart Streamlit to see updated data.")


if __name__ == "__main__":
    asyncio.run(main())
