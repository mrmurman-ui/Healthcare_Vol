async def main():
    from app.core.database import AsyncSessionLocal
    print("="*55)
    print("[Announcements] Seeding 10 realistic announcements...")
    async with AsyncSessionLocal() as session:
        await session.execute(text(
            "UPDATE announcements SET is_active=false WHERE created_by='demo_seed'"
        ))
        ok = 0
        for atype, title, content, active, start, end in ANNOUNCEMENTS:
            try:
                await session.execute(text("""
                    INSERT INTO announcements
                        (id, title, content, announcement_type, is_active,
                         start_date, end_date, created_at, updated_at,
                         created_by, updated_by)
                    VALUES
                        (gen_random_uuid(), :title, :content, :atype, :active,
                         :start, :end, NOW(), NOW(), 'demo_seed', 'demo_seed')
                """), {"title": title, "content": content, "atype": atype,
                       "active": active, "start": start, "end": end})
                ok += 1
            except Exception as e:
                print(f"  [WARN] {title[:30]}: {e}")
        await session.commit()
    print(f"  [OK] {ok} announcements seeded")
    print("[DONE]")

if __name__ == "__main__":
    asyncio.run(main())
